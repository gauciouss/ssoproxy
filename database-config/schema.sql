-- MSSQL 2022
CREATE TABLE SSO_PROXY_TARGETS (     
    HOST_ID VARCHAR(50) PRIMARY KEY,   
    HOST VARCHAR(MAX) UNIQUE NOT NULL,
    REVERSE_PROXY_HOST VARCHAR(MAX) NOT NULL,
    ORDER INT NOT NULL,
    SYSTEM_NAME NVARCHAR(MAX) NOT NULL,
    IS_TERMINATED BOOLEAN DEFAULT TRUE, -- 設定預設值為 TRUE，表示預設情況下該目標是受保護的，會檢查 SSO Token是否合法；FALSE則不會檢查 SSO Token是否合法，直接允許訪問
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

-- 免驗證白名單表格，存放不需要驗證 SSO Token 的路徑， 例如 /health、/metrics、/js 等，這些路徑通常是用於監控或健康檢查的，不需要進行 SSO 驗證
CREATE TABLE SSO_WHITE_LIST (
    HOST_ID VARCHAR(50) PRIMARY KEY,
    FILTER_PATH VARCHAR(MAX) NOT NULL,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    FOREIGN KEY (HOST_ID) REFERENCES SSO_PROXY_TARGETS(HOST_ID) ON DELETE CASCADE
);

